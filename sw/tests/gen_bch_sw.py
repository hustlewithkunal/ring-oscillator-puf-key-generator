"""Generate sw/tests/bch_sw.S: BCH(15,7,2) decoding in RV32I software, for the
hardware/software comparison. The program decodes 64 received words taken from
model/vectors/bch_dec.mem (weights 0..3), compares every result with the golden model,
and brackets the decode loop with two stores to MARK so the testbench can count cycles.
Result word at RESULT: number of mismatches (0 = all correct).

Run from the project root:  python sw/tests/gen_bch_sw.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
N_TESTS = 64

EXP = [1, 2, 4, 8, 3, 6, 12, 11, 5, 10, 7, 14, 15, 13, 9]
LOG = [0] * 16
for i, v in enumerate(EXP):
    LOG[v] = i

PROGRAM = r'''# GENERATED by sw/tests/gen_bch_sw.py -- BCH(15,7,2) decoder in RV32I software.
# Same algorithm as the hardware: syndromes S1, S3; Peterson L1 = S1, L2 = S3/S1 + S1^2;
# Chien search over 15 positions; ok = (roots == deg Lambda). GF(2^4) multiply via
# log/antilog tables (the core has no multiply instruction, and it is not needed).

.equ RESULT, 0x1FC0
.equ MARK,   0x1F80

start:  li   sp, 0x1F00
        la   s3, expt               # antilog table (31 entries, index 0..30)
        la   s4, logt               # log table
        la   s0, tests
        li   s1, NTESTS
        li   s2, 0                  # mismatches
        li   t0, MARK
        sw   zero, 0(t0)            # ---- start of the timed region
loop:   lw   a0, 0(s0)              # received word
        call decode
        lw   t0, 4(s0)              # expected corrected word
        lw   t1, 8(s0)              # expected ok
        beq  a0, t0, c1
        addi s2, s2, 1
c1:     beq  a1, t1, c2
        addi s2, s2, 1
c2:     addi s0, s0, 12
        addi s1, s1, -1
        bnez s1, loop
        li   t0, MARK
        sw   zero, 0(t0)            # ---- end of the timed region
        li   t0, RESULT
        sw   s2, 0(t0)
        ebreak

# decode(a0 = received) -> a0 = corrected word, a1 = ok
decode: mv   s11, ra
        mv   s5, a0
        li   s6, 0                  # S1
        li   s7, 0                  # S3
        li   t3, 0                  # i
        li   t4, 0                  # 3i mod 15
syn:    srl  t5, s5, t3
        andi t5, t5, 1
        beqz t5, syn_n
        add  t6, s3, t3
        lbu  t6, 0(t6)
        xor  s6, s6, t6
        add  t6, s3, t4
        lbu  t6, 0(t6)
        xor  s7, s7, t6
syn_n:  addi t4, t4, 3
        li   t6, 15
        blt  t4, t6, syn_m
        addi t4, t4, -15
syn_m:  addi t3, t3, 1
        blt  t3, t6, syn
        bnez s6, peter
        mv   a0, s5                 # S1 = 0: no error if S3 = 0, else uncorrectable
        seqz a1, s7
        mv   ra, s11
        ret
peter:  add  t0, s4, s6             # S1^-1 = alpha^(15 - log S1)
        lbu  t0, 0(t0)
        li   t1, 15
        sub  t1, t1, t0
        add  t1, s3, t1
        lbu  s8, 0(t1)
        mv   a0, s7                 # L2 = S3 * S1^-1 + S1 * S1
        mv   a1, s8
        call mul
        mv   s9, a0
        mv   a0, s6
        mv   a1, s6
        call mul
        xor  s9, s9, a0
        li   s10, 0                 # error mask
        li   a4, 0                  # roots
        li   a2, 0                  # position i
chien:  li   t0, 15                 # x = alpha^(15 - i), x^2 = alpha^(30 - 2i)
        sub  t0, t0, a2
        add  t0, s3, t0
        lbu  a1, 0(t0)
        mv   a0, s6
        call mul
        mv   a5, a0
        li   t0, 30
        sub  t0, t0, a2
        sub  t0, t0, a2
        add  t0, s3, t0
        lbu  a1, 0(t0)
        mv   a0, s9
        call mul
        xor  a5, a5, a0
        xori a5, a5, 1
        bnez a5, chien_n
        li   t0, 1                  # root: bit i is in error
        sll  t0, t0, a2
        or   s10, s10, t0
        addi a4, a4, 1
chien_n: addi a2, a2, 1
        li   t0, 15
        blt  a2, t0, chien
        li   t0, 1                  # deg Lambda = 2 if L2 != 0 else 1
        beqz s9, deg1
        li   t0, 2
deg1:   sub  t1, a4, t0
        seqz a1, t1                 # ok = (roots == deg)
        mv   a0, s5
        beqz a1, dec_out
        xor  a0, s5, s10
dec_out: mv  ra, s11
        ret

# mul(a0, a1) -> a0 = a0 * a1 in GF(2^4), via log/antilog tables
mul:    beqz a0, mul0
        beqz a1, mul0
        add  t0, s4, a0
        lbu  t0, 0(t0)
        add  t1, s4, a1
        lbu  t1, 0(t1)
        add  t0, t0, t1
        add  t0, s3, t0
        lbu  a0, 0(t0)
        ret
mul0:   li   a0, 0
        ret

.align 2
expt:
EXPWORDS
logt:
LOGWORDS
tests:
TESTWORDS
'''


def pack_bytes(values):
    values = list(values) + [0] * (-len(values) % 4)
    return "\n".join("        .word 0x{:08x}".format(
        values[k] | values[k + 1] << 8 | values[k + 2] << 16 | values[k + 3] << 24)
        for k in range(0, len(values), 4))


def main():
    rows = [l.strip() for l in open(os.path.join(ROOT, "model", "vectors", "bch_dec.mem"))
            if l.strip() and not l.startswith("//")]
    # spread the tests over the file: weight-0/1/2 region and the weight-3 region
    picks = [rows[k * (15488 // 48)] for k in range(48)] + [rows[15488 + k * 120] for k in range(16)]
    tests = []
    for r in picks:
        v = int(r, 16)
        received = (v >> 52) & 0x7FFF
        corrected = (v >> 4) & 0x7FFF
        ok = v & 1
        tests.append("        .word 0x{:04x}, 0x{:04x}, {}".format(received, corrected, ok))
    expt = [EXP[k % 15] for k in range(31)]
    src = (PROGRAM.replace("NTESTS", str(N_TESTS))
           .replace("EXPWORDS", pack_bytes(expt))
           .replace("LOGWORDS", pack_bytes(LOG))
           .replace("TESTWORDS", "\n".join(tests)))
    out = os.path.join(ROOT, "sw", "tests", "bch_sw.S")
    with open(out, "w", newline="\n") as f:
        f.write(src)
    print("wrote", os.path.relpath(out, ROOT), "with", len(tests), "test words")


if __name__ == "__main__":
    main()
