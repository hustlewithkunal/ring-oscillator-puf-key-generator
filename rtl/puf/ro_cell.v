// Configurable ring oscillator for the Zynq-7000 / 7-series fabric (synthesis version).
// Simulation uses rtl/puf/sim/ro_cell_sim.v instead (same ports).
//
// Three inverting LUT stages (3 inversions = oscillates when en = 1):
//   stage 0  O = ~(en & (cfg[0] ? I1 : I0))      LUT4, enable + feedback
//   stage 1  O = ~(cfg[1] ? I1 : I0)             LUT3
//   stage 2  O = ~(cfg[2] ? I1 : I0)             LUT3
// I0 and I1 of every stage are driven by the SAME net; cfg only chooses which
// physical LUT input pin the signal travels through. Different pins have different
// delays, so each RO has 8 slightly different frequencies (configurable RO,
// Maiti & Schaumont 2011). cfg = 000 is the baseline RO.
//
// A toggle flip-flop in the same slice divides the RO frequency by 2, so the
// counters and the selection multiplexers only see a clean half-rate square wave.
// All cells are DONT_TOUCH and placed with explicit LOC/BEL/LOCK_PINS constraints
// (constraints/puf_placement.xdc, generated by scripts/gen_puf_xdc.py), so every
// RO in every array has exactly the same structure.

`timescale 1ns / 1ps

(* DONT_TOUCH = "TRUE" *)
module ro_cell (
    input  wire       en,       // 1 = oscillate, 0 = stop (loop output held at 1)
    input  wire [2:0] cfg,      // path configuration (static while running)
    output wire       tog       // RO frequency / 2
);

    (* DONT_TOUCH = "TRUE", ALLOW_COMBINATORIAL_LOOPS = "TRUE" *) wire n0, n1, n2;
    (* DONT_TOUCH = "TRUE" *) wire t_q, t_d;

    (* DONT_TOUCH = "TRUE" *)
    LUT4 #(.INIT(16'h35FF)) u_s0 (.O(n0), .I0(n2), .I1(n2), .I2(cfg[0]), .I3(en));
    (* DONT_TOUCH = "TRUE" *)
    LUT3 #(.INIT(8'h35))    u_s1 (.O(n1), .I0(n0), .I1(n0), .I2(cfg[1]));
    (* DONT_TOUCH = "TRUE" *)
    LUT3 #(.INIT(8'h35))    u_s2 (.O(n2), .I0(n1), .I1(n1), .I2(cfg[2]));

    // divide-by-2 toggle flip-flop clocked by the RO
    (* DONT_TOUCH = "TRUE" *)
    LUT1 #(.INIT(2'b01))    u_ti (.O(t_d), .I0(t_q));
    (* DONT_TOUCH = "TRUE" *)
    FDRE #(.INIT(1'b0))     u_tf (.C(n2), .CE(1'b1), .R(1'b0), .D(t_d), .Q(t_q));

    assign tog = t_q;

endmodule
