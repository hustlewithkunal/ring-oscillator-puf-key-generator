"""Generate constraints/puf_placement.xdc: exact placement of every RO in every array.

Layout (Zynq-7010, SLICEL columns of CLBLL tiles only, so every RO sits in an
identical slice type):
  * one RO per slice:  stage 0 -> A6LUT, stage 1 -> B6LUT, stage 2 -> C6LUT,
                       toggle inverter -> D6LUT, toggle flip-flop -> DFF
  * pair p = (RO 2p, RO 2p+1) in vertically adjacent slices of the same column
  * array a uses columns COLS and rows ROW_BASE[a] .. ROW_BASE[a] + 31
    (8 columns x 16 pairs = 128 pairs); arrays sit at three heights of the die
  * LOCK_PINS fixes which physical LUT pin carries each logical input, so the
    configurable paths (I0 vs I1) are the same in every RO
  * all RO slices form one Pblock with EXCLUDE_PLACEMENT: no other logic may use
    the spare resources there

Run from the project root:   python scripts/gen_puf_xdc.py
"""

import os

COLS = [14, 15, 18, 19, 22, 23, 26, 27]      # SLICEL columns in CLBLL tiles
ROW_BASE = [0, 34, 68]                        # one band of 32 rows per array
PAIRS_PER_COL = 16
INST = "u_puf/g_arr[{a}].u_arr/g_ro[{i}].u_ro/{cell}"

# logical LUT input -> physical pin (identical for every RO)
LOCK = {
    "u_s0": "I0:A2 I1:A5 I2:A1 I3:A3",       # feedback copies on A2 / A5, cfg on A1, en on A3
    "u_s1": "I0:A2 I1:A5 I2:A1",
    "u_s2": "I0:A2 I1:A5 I2:A1",
    "u_ti": "I0:A2",
}
BEL = {"u_s0": "A6LUT", "u_s1": "B6LUT", "u_s2": "C6LUT", "u_ti": "D6LUT", "u_tf": "DFF"}


def ro_site(a, i):
    p, r = divmod(i, 2)
    col = COLS[p // PAIRS_PER_COL]
    row = ROW_BASE[a] + 2 * (p % PAIRS_PER_COL) + r
    return "SLICE_X{}Y{}".format(col, row)


def main(n_arr=3):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "constraints", "puf_placement.xdc")
    lines = [
        "# GENERATED by scripts/gen_puf_xdc.py -- do not edit by hand.",
        "# Placement of {} RO arrays x 256 configurable ROs (see the script for the layout).".format(n_arr),
        "",
        "# The ring oscillators are intentional combinational loops.",
        "set_property SEVERITY {Warning} [get_drc_checks LUTLP-1]",
        "",
        "create_pblock pb_ro",
    ]
    for a in range(n_arr):
        for col in COLS:
            lines.append("resize_pblock pb_ro -add {{SLICE_X{c}Y{y0}:SLICE_X{c}Y{y1}}}".format(
                c=col, y0=ROW_BASE[a], y1=ROW_BASE[a] + 2 * PAIRS_PER_COL - 1))
    lines += [
        "add_cells_to_pblock pb_ro [get_cells -hierarchical -filter {NAME =~ u_puf/g_arr[*].u_arr/g_ro[*].u_ro}]",
        "set_property EXCLUDE_PLACEMENT true [get_pblocks pb_ro]",
        "",
    ]
    for a in range(n_arr):
        lines.append("# ---- array {}".format(a))
        for i in range(256):
            site = ro_site(a, i)
            for cell, bel in BEL.items():
                name = INST.format(a=a, i=i, cell=cell)
                lines.append("set_property BEL {} [get_cells {{{}}}]".format(bel, name))
                lines.append("set_property LOC {} [get_cells {{{}}}]".format(site, name))
                if cell in LOCK:
                    lines.append("set_property LOCK_PINS {{{}}} [get_cells {{{}}}]".format(LOCK[cell], name))
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(out, root), "({} lines)".format(len(lines)))


if __name__ == "__main__":
    main()
