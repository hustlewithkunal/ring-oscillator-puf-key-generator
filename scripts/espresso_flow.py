"""ESPRESSO flow for the GF(2^4) multiplier and inverse.

For each truth table in model/vectors/espresso/*.pla this script:
  1. runs ESPRESSO (two-level logic minimisation)       -> <name>.min.pla
  2. checks the minimised cover against the golden model for every input
  3. writes a sum-of-products Verilog module             -> rtl/gf/<module>.v
  4. prints product-term / literal statistics for the report

Run from the project root:   python scripts/espresso_flow.py [--exact]
ESPRESSO is looked up in: $ESPRESSO, tools/espresso/espresso(.exe), then PATH.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from model import gf16 as gf  # noqa: E402

PLA_DIR = os.path.join(ROOT, "model", "vectors", "espresso")
RTL_DIR = os.path.join(ROOT, "rtl", "gf")

# name -> (Verilog module, reference function on the packed input, description)
FUNCTIONS = {
    "gf_mul": ("gf16_mul_sop", lambda x: gf.MUL_TABLE[x >> 4][x & 0xF], "GF(2^4) multiplier p = a * b"),
    "gf_inv": ("gf16_inv_sop", lambda x: gf.INV_TABLE[x], "GF(2^4) inverse y = a^-1 (inv(0) = 0)"),
}


def find_espresso():
    candidates = [os.environ.get("ESPRESSO"),
                  os.path.join(ROOT, "tools", "espresso", "espresso.exe"),
                  os.path.join(ROOT, "tools", "espresso", "espresso"),
                  shutil.which("espresso")]
    for c in candidates:
        if c and os.path.isfile(c):
            return c
    sys.exit("ESPRESSO not found. Build it into tools/espresso/ (see docs/ESPRESSO_Setup.md) "
             "or set the ESPRESSO environment variable.")


def parse_pla(text):
    """Return (input names, output names, list of (input cube, output bits)) from a PLA."""
    ilb, ob, cubes = [], [], []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        if line.startswith(".ilb"):
            ilb = line.split()[1:]
        elif line.startswith(".ob"):
            ob = line.split()[1:]
        elif line.startswith("."):
            continue
        else:
            inp, out = line.split()
            cubes.append((inp, out))
    return ilb, ob, cubes


def cube_matches(cube, value, n_in):
    """Does the input cube (string over 0/1/-, MSB first) contain this input value?"""
    for pos, ch in enumerate(cube):
        bit = (value >> (n_in - 1 - pos)) & 1
        if (ch == "1" and bit == 0) or (ch == "0" and bit == 1):
            return False
    return True


def evaluate_cover(cubes, value, n_in, n_out):
    out = 0
    for inp, outs in cubes:
        if cube_matches(inp, value, n_in):
            for k, ch in enumerate(outs):
                if ch == "1":
                    out |= 1 << (n_out - 1 - k)
    return out


def verify(cubes, n_in, n_out, reference):
    errors = [v for v in range(1 << n_in) if evaluate_cover(cubes, v, n_in, n_out) != reference(v)]
    return errors


def _signal(name):
    """'a3' -> ('a', 3)."""
    m = re.fullmatch(r"([A-Za-z_]+)(\d+)", name)
    if not m:
        raise ValueError("PLA signal names must look like a3, b0, p2: " + name)
    return m.group(1), int(m.group(2))


def _ports(names):
    """Group bit names into buses: ['a3',..,'b0'] -> [('a', 4), ('b', 4)] in order of appearance."""
    widths = {}
    for n in names:
        bus, bit = _signal(n)
        widths[bus] = max(widths.get(bus, 0), bit + 1)
    return list(widths.items())


def stats(cubes):
    literals = sum(sum(ch != "-" for ch in inp) for inp, _ in cubes)
    per_output = [sum(out[k] == "1" for _, out in cubes) for k in range(len(cubes[0][1]))] if cubes else []
    return {"terms": len(cubes), "literals": literals, "per_output": per_output}


def to_verilog(module, description, source, ilb, ob, cubes):
    s = stats(cubes)
    lines = [
        "// Auto-generated by scripts/espresso_flow.py -- do not edit by hand.",
        "// {}".format(description),
        "// Source: {} (minimised by ESPRESSO)".format(source),
        "// Two-level sum of products: {} product terms, {} literals.".format(s["terms"], s["literals"]),
        "",
        "`timescale 1ns / 1ps",
        "",
        "module {} (".format(module),
    ]
    ports = ["    input  wire [{}:0] {}".format(w - 1, bus) for bus, w in _ports(ilb)]
    ports += ["    output wire [{}:0] {}".format(w - 1, bus) for bus, w in _ports(ob)]
    lines.append(",\n".join(ports))
    lines.append(");")
    lines.append("")
    if cubes:
        lines.append("    wire [{}:0] t;  // product terms (shared between outputs)".format(len(cubes) - 1))
        lines.append("")
    for i, (inp, _) in enumerate(cubes):
        lits = []
        for name, ch in zip(ilb, inp):
            bus, bit = _signal(name)
            if ch == "1":
                lits.append("{}[{}]".format(bus, bit))
            elif ch == "0":
                lits.append("~{}[{}]".format(bus, bit))
        lines.append("    assign t[{}] = {};".format(i, " & ".join(lits) if lits else "1'b1"))
    lines.append("")
    for k, name in enumerate(ob):
        bus, bit = _signal(name)
        terms = ["t[{}]".format(i) for i, (_, out) in enumerate(cubes) if out[k] == "1"]
        lines.append("    assign {}[{}] = {};".format(bus, bit, " | ".join(terms) if terms else "1'b0"))
    lines += ["", "endmodule", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exact", action="store_true", help="use ESPRESSO's exact minimisation (-Dexact)")
    args = parser.parse_args()

    espresso = find_espresso()
    os.makedirs(RTL_DIR, exist_ok=True)
    print("ESPRESSO:", espresso)
    print("{:<8} {:>9} {:>9} {:>9}  {}".format("function", "in terms", "out terms", "literals", "terms per output"))
    failed = False
    for name, (module, reference, description) in FUNCTIONS.items():
        src = os.path.join(PLA_DIR, name + ".pla")
        cmd = [espresso] + (["-Dexact"] if args.exact else []) + [src]
        result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
        if result.returncode != 0:
            sys.exit("ESPRESSO failed on {}:\n{}".format(src, result.stderr))
        with open(os.path.join(PLA_DIR, name + ".min.pla"), "w", newline="\n") as f:
            f.write(result.stdout)

        with open(src) as f:
            _, _, original = parse_pla(f.read())
        ilb, ob, cubes = parse_pla(result.stdout)
        errors = verify(cubes, len(ilb), len(ob), reference)
        if errors:
            failed = True
            print("ERROR: {} minimised cover is wrong for {} inputs, e.g. {}".format(name, len(errors), errors[:5]))
            continue

        on_terms = sum("1" in out for _, out in original)
        s = stats(cubes)
        print("{:<8} {:>9} {:>9} {:>9}  {}".format(name, on_terms, s["terms"], s["literals"], s["per_output"]))
        out_path = os.path.join(RTL_DIR, module + ".v")
        with open(out_path, "w", newline="\n") as f:
            f.write(to_verilog(module, description, os.path.relpath(src, ROOT).replace(os.sep, "/"), ilb, ob, cubes))
        print("         verified exhaustively ({} inputs) -> {}".format(1 << len(ilb), os.path.relpath(out_path, ROOT)))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
